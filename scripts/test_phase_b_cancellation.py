"""Capture/request and post-capture job cancellation probes for the 4.70 route.

No job identifier is exposed during conversion. This test deliberately reports
that observability gap rather than calling post-capture cancellation conversion
interruption. Use a fresh output directory; all wire traffic is retained.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import queue
import subprocess
import threading
import time
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


class Client:
    def __init__(self, args, out):
        self.log = (out / 'wire.jsonl').open('w', encoding='utf-8')
        self.errors = (out / 'stderr.log').open('w', encoding='utf-8')
        self.process = subprocess.Popen([str(args.binary.resolve()), '--resources',
            str(args.resources.resolve())], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=self.errors, env=dict(os.environ))
        self.responses = queue.Queue()
        self.counter = 0
        def read():
            for line in self.process.stdout:
                self.responses.put(json.loads(line))
        self.reader = threading.Thread(target=read, daemon=True)
        self.reader.start()

    def send(self, method, params, notification=False):
        self.counter += 1
        request = dict(jsonrpc='2.0', method=method, params=params)
        if not notification:
            request['id'] = self.counter
        self.log.write(json.dumps(dict(time=time.monotonic(), sent=request))+'\n')
        self.log.flush()
        self.process.stdin.write((json.dumps(request)+'\n').encode())
        self.process.stdin.flush()
        return self.counter

    def receive(self, ident):
        deadline = time.monotonic()+150
        while time.monotonic() < deadline:
            response = self.responses.get(timeout=max(.01, deadline-time.monotonic()))
            self.log.write(json.dumps(dict(time=time.monotonic(), received=response))+'\n')
            self.log.flush()
            if response.get('id') == ident:
                return response
        raise TimeoutError(ident)

    def call(self, tool, args):
        response = self.receive(self.send('tools/call', dict(name=tool, arguments=args)))
        assert 'result' in response, response
        return response['result']['structuredContent']

    def close(self):
        self.process.stdin.close()
        try:
            assert self.process.wait(timeout=15) == 0
        finally:
            if self.process.poll() is None:
                self.process.kill()
                self.process.wait()
            self.reader.join(timeout=2)
            self.log.close()
            self.errors.close()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--binary', type=Path, required=True)
    p.add_argument('--resources', type=Path, required=True)
    p.add_argument('--host-sha256', required=True)
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    assert sha(args.binary) == args.host_sha256, 'host hash mismatch'
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=False)
    source = ROOT/'tests/phase_b/notes.mscx'
    # Repeat a supported measure without reusing element identities. Retain the
    # generated bytes/hash so this stress input can be replayed independently.
    tree = ET.parse(source)
    staff = tree.find('./Score/Staff')
    measures = list(staff.findall('Measure'))
    for _ in range(511):
        for measure in measures:
            staff.append(copy.deepcopy(measure))
    for parent in tree.iter():
        for eid in list(parent.findall('eid')):
            parent.remove(eid)
    stress = out/'stress.mscx'
    tree.write(stress, encoding='utf-8', xml_declaration=True)
    largest = max((f for f in (ROOT/'fixtures/golden').iterdir() if f.is_file()), key=lambda f: f.stat().st_size)
    preflight = dict(host_sha256=args.host_sha256, engine_revision=subprocess.check_output(
        ['git','-C',str(ROOT/'vendor/musescore'),'rev-parse','HEAD'], text=True).strip(),
        sources={str(f):sha(f) for f in (source, stress, largest)},
        assets={str(f.relative_to(args.resources)):sha(f) for f in sorted(args.resources.rglob('*')) if f.is_file()})
    (out/'preflight.json').write_text(json.dumps(preflight, indent=2))
    client = Client(args, out)
    records = []
    def export_args(doc, path, fmt='mscx'):
        return dict(document=doc, action='start', kind='score',
            options=dict(format=fmt, native_version='4.70'),
            destination=dict(kind='file',path=str(path)))
    def terminal(job):
        deadline = time.monotonic()+150
        states = []
        while time.monotonic()<deadline:
            value = client.call('runtime_job', dict(job=job,action='get'))
            assert value['ok'], value
            status = value['status']
            states.append(status['state'])
            if status['state'] in ('succeeded','failed','cancelled'):
                return status, states
            time.sleep(.001)
        raise TimeoutError(job)
    try:
        client.receive(client.send('initialize', dict(protocolVersion='2024-11-05',
            capabilities={},clientInfo=dict(name='phase-b-cancellation',version='1'))))
        client.send('notifications/initialized', {}, notification=True)
        info = client.call('runtime_info', {})
        (out/'runtime.json').write_text(json.dumps(info, indent=2))
        for fixture in (largest, stress):
            opened = client.call('score_open', dict(path=str(fixture)))
            assert opened['ok'], opened
            doc = opened['document']
            for fmt in ('mscx','mscz'):
                # Measure full capture+start latency and establish the route's
                # actual success/refusal before attempting cancellation.
                path = out/f'{fixture.stem}-{fmt}-control.{fmt}'
                start = time.monotonic()
                baseline = client.call('score_export', export_args(doc,path,fmt))
                latency = time.monotonic()-start
                assert baseline['ok'], baseline
                control, states = terminal(baseline['job'])
                records.append(dict(fixture=fixture.name, format=fmt, probe='control',
                    start_seconds=latency, status=control, states=states))
                # Interleave notification at several fractions of observed
                # latency. Timing alone does not identify the conversion phase.
                for fraction in (.1,.5,.8):
                    path = out/f'{fixture.stem}-{fmt}-request-{fraction}.{fmt}'
                    request = client.send('tools/call',dict(name='score_export',arguments=export_args(doc,path,fmt)))
                    time.sleep(latency*fraction)
                    client.send('notifications/cancelled',dict(requestId=request,reason='4.70 capture probe'),notification=True)
                    response = client.receive(request)
                    record = dict(fixture=fixture.name,format=fmt,probe='request-cancel',fraction=fraction,response=response)
                    if 'error' in response:
                        assert response['error']['code'] == -32800, response
                        assert not path.exists(), 'cancelled request published destination'
                    else:
                        value = response['result']['structuredContent']
                        if value['ok']:
                            cancelled = client.call('runtime_job', dict(job=value['job'],action='cancel'))
                            status, states = terminal(value['job'])
                            record.update(cancel_response=cancelled,status=status,states=states)
                            if status['state']=='cancelled':
                                assert status['artifacts']==[] and not path.exists(), status
                        else:
                            assert not path.exists(), value
                    record['destination_exists'] = path.exists()
                    records.append(record)
                path = out/f'{fixture.stem}-{fmt}-job-cancel.{fmt}'
                started = client.call('score_export',export_args(doc,path,fmt))
                assert started['ok'], started
                cancel = client.call('runtime_job',dict(job=started['job'],action='cancel'))
                status, states = terminal(started['job'])
                assert status['state'] in ('cancelled','failed','succeeded'), status
                if status['state']=='cancelled':
                    assert status['artifacts']==[] and not path.exists(), status
                records.append(dict(fixture=fixture.name,format=fmt,probe='job-cancel',cancel_response=cancel,status=status,states=states,destination_exists=path.exists()))
            assert client.call('score_close',dict(document=doc))['ok']
        for fmt in ('mscx','mscz'):
            probes = [r for r in records if r.get('fixture') == 'stress.mscx' and r.get('format') == fmt]
            assert any(r['probe']=='control' and r['status']['state']=='succeeded' for r in probes)
            assert any(r['probe']=='request-cancel' and 'error' in r.get('response',{}) for r in probes), 'no pending request cancelled'
            assert any(r['probe']=='job-cancel' and r['status']['state']=='cancelled' for r in probes), 'no job cancelled'
        doc = client.call('score_open',dict(path=str(source)))['document']
        recovery = out/'recovery.mscx'
        started = client.call('score_export',export_args(doc,recovery))
        status, states = terminal(started['job'])
        assert status['state']=='succeeded' and recovery.is_file(), status
        assert ET.parse(recovery).getroot().attrib['version']=='4.70'
        records.append(dict(probe='same-session-recovery',status=status,states=states))
    finally:
        client.close()
        (out/'results.json').write_text(json.dumps(dict(records=records,
            conversion_stage_observed=False, runtime_job_during_conversion='unavailable: job ID returned after capture',
            deadline='not executed: production deadline fixed at 120000 ms; no public override',
            working_budget='no public max_working_bytes override'),indent=2))
    manifest = {str(f.relative_to(out)):sha(f) for f in sorted(out.rglob('*')) if f.is_file()}
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2))
    print(json.dumps(dict(output=str(out),records=len(records),conversion_stage_observed=False)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
